#!/usr/bin/env node
// Writes echo/Services/Cuelume/CuelumeRecipes.swift from a built Cuelume checkout, so Echo's Swift
// synthesiser plays exactly the layers Cuelume's own engine does.
//
//   git clone https://github.com/danielwh2/cuelume.git /path/to/cuelume
//   (cd /path/to/cuelume && npm install --ignore-scripts && npm run build)
//   node scripts/generate-cuelume-recipes.mjs /path/to/cuelume
//
// The helpers Cuelume spells materials with (`struck`, `knock`, `note`, ...) are expanded into
// plain layers here. Fields Echo does not use are dropped: `walk` and `note` only matter for
// quick repeats, and `stretch` only for `count` with a duration. Anything new in Cuelume's recipe
// format stops the script, so the Swift renderer can learn it first.
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const checkout = process.argv[2];
if (!checkout) {
  console.error("usage: node scripts/generate-cuelume-recipes.mjs <path to a built cuelume checkout>");
  process.exit(1);
}
const root = resolve(checkout);
const { THEMES } = await import(pathToFileURL(resolve(root, "dist/sounds/themes.js")).href);
const version = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8")).version;
let commit = "unknown";
try {
  commit = execFileSync("git", ["-C", root, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
} catch {}

const RECIPE_KEYS = new Set(["masterGain", "layers", "vary", "room", "release", "walk"]);
const LAYER_KEYS = new Set([
  "kind", "waveform", "frequency", "filterType", "filterFrequency", "filterQ", "attack", "decay", "peak",
  "offset", "glideTo", "glideTime", "from", "stretch", "note",
]);

const num = (value) => {
  if (typeof value !== "number" || !Number.isFinite(value)) throw new Error(`not a number: ${value}`);
  const text = String(value);
  return /[.e]/.test(text) ? text : `${text}.0`;
};

function layer(l, where) {
  for (const key of Object.keys(l)) if (!LAYER_KEYS.has(key)) throw new Error(`${where}: unknown layer field "${key}"`);
  if (l.stretch && !where.endsWith(".count")) throw new Error(`${where}: stretch outside count`);
  const args = [];
  if (l.kind === "tone") {
    if (l.waveform !== "sine") throw new Error(`${where}: waveform ${l.waveform}`);
    args.push(num(l.frequency));
  } else if (l.kind === "noise") {
    if (!["bandpass", "lowpass", "highpass"].includes(l.filterType)) throw new Error(`${where}: filter ${l.filterType}`);
    args.push(`.${l.filterType}`, num(l.filterFrequency));
    if (l.filterQ !== undefined) args.push(`q: ${num(l.filterQ)}`);
  } else {
    throw new Error(`${where}: kind ${l.kind}`);
  }
  args.push(`attack: ${num(l.attack)}`, `decay: ${num(l.decay)}`, `peak: ${num(l.peak)}`);
  if (l.offset) args.push(`offset: ${num(l.offset)}`);
  if (l.glideTo !== undefined) args.push(`glideTo: ${num(l.glideTo)}`);
  if (l.glideTime !== undefined) args.push(`glideTime: ${num(l.glideTime)}`);
  if (l.from) args.push(`from: .${l.from}`);
  return `.${l.kind}(${args.join(", ")})`;
}

const layers = (list, where, indent) =>
  `[\n${list.map((l) => `${indent}  ${layer(l, where)},`).join("\n")}\n${indent}]`;

function recipe(r, where) {
  for (const key of Object.keys(r)) if (!RECIPE_KEYS.has(key)) throw new Error(`${where}: unknown recipe field "${key}"`);
  const indent = "      ";
  const parts = [`masterGain: ${num(r.masterGain)}`, `layers: ${layers(r.layers, where, indent)}`];
  if (r.release) parts.push(`release: ${layers(r.release, where, indent)}`);
  if (r.room !== undefined) parts.push(`room: ${num(r.room)}`);
  if (r.vary) parts.push(`vary: CuelumeVariation(pitch: ${num(r.vary.pitch)}, level: ${num(r.vary.level)})`);
  return `CuelumeRecipe(\n${indent}${parts.join(`,\n${indent}`)}\n    )`;
}

const swiftTheme = (name) => (name === "default" ? "standard" : name);
const cues = Object.keys(THEMES.default);
for (const [name, theme] of Object.entries(THEMES)) {
  const missing = cues.filter((cue) => !theme[cue]);
  if (missing.length) throw new Error(`${name} is missing ${missing.join(", ")}`);
}

const out = `// Generated by scripts/generate-cuelume-recipes.mjs from Cuelume ${version} (${commit}). Do not edit.
//
// Cuelume — https://github.com/danielwh2/cuelume
// Copyright (c) 2026 Daniel Belyi. MIT License; see Cuelume-LICENSE.txt beside this file.

// swiftlint:disable file_length

extension CuelumeTheme {
  /// Every cue's recipe in this theme, exactly as Cuelume ${version} defines it.
  func recipe(for cue: CuelumeCue) -> CuelumeRecipe {
    switch self {
${Object.keys(THEMES).map((name) => `    case .${swiftTheme(name)}: return Self.${swiftTheme(name)}Recipe(cue)`).join("\n")}
    }
  }
${Object.entries(THEMES)
  .map(
    ([name, theme]) => `
  // MARK: - ${name}

  private static func ${swiftTheme(name)}Recipe(_ cue: CuelumeCue) -> CuelumeRecipe {
    switch cue {
${cues.map((cue) => `    case .${cue}:\n      return ${recipe(theme[cue], `${name}.${cue}`).replace(/\n/g, "\n  ")}`).join("\n")}
    }
  }`,
  )
  .join("\n")}
}
`;

const target = resolve(new URL("..", import.meta.url).pathname, "echo/Services/Cuelume/CuelumeRecipes.swift");
writeFileSync(target, out);
console.log(`wrote ${target} from Cuelume ${version} (${commit})`);
